// Build the mobile app (apps/mobile) into dist/site, the main page:
//   index.html            data, CSS and JS inlined, so it also works from file://
//   manifest.webmanifest, sw.js, icon.svg, icon-180/192/512.png, icon-maskable-512.png
// Runs after scripts/build.ts (it reads dist/bundle.json):
//   pnpm build

import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';
import { shippedData, sizeByDiscipline } from './app-data.ts';
import type { Bundle } from './bundle.ts';
import { ROOT, green, red } from './lib.ts';

const APP = join(ROOT, 'apps', 'mobile');
const DIST = join(ROOT, 'dist');
const SITE = join(DIST, 'site');
/** PNG icons copied from apps/mobile/icons (pnpm icons makes them from the SVGs there). */
const ICON_FILES = ['icon-180.png', 'icon-192.png', 'icon-512.png', 'icon-maskable-512.png'] as const;

interface EsbuildLike {
  build(options: Record<string, unknown>): Promise<{ outputFiles?: { text: string }[] }>;
  transform(code: string, options: Record<string, unknown>): Promise<{ code: string }>;
}

/** The esbuild that tsx already depends on; no extra dependency. */
function loadEsbuild(): EsbuildLike {
  const require = createRequire(import.meta.url);
  return createRequire(require.resolve('tsx/package.json'))('esbuild') as EsbuildLike;
}

function manifest(): string {
  return JSON.stringify(
    {
      name: '投稿下一站',
      short_name: '下一站',
      description: '投稿截止与规则：计算机为主，覆盖工程、医学等学科。下一个截止是什么、之后还能改什么，每条都附官网原句。',
      lang: 'zh-CN',
      start_url: './',
      scope: './',
      display: 'standalone',
      background_color: '#F2F2F7',
      theme_color: '#F2F2F7',
      icons: [
        { src: 'icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
        { src: 'icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
        { src: 'icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
        { src: 'icon.svg', sizes: 'any', type: 'image/svg+xml' },
      ],
    },
    null,
    2,
  );
}

function serviceWorker(version: string): string {
  const shell = ['./', './index.html', './stats.js', './manifest.webmanifest', './icon.svg', ...ICON_FILES.map((f) => `./${f}`)];
  return `// Copyright (c) 2026 Zayier Xie. SPDX-License-Identifier: AGPL-3.0-or-later

// Generated by scripts/build-app.ts. Caches the app shell (the page carries
// the data) so the app opens offline; pages are fetched fresh when online.
const CACHE = 'nextvenue-${version}';
const SHELL = ${JSON.stringify(shell)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(SHELL)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  const keep = (res) => {
    if (res.ok) {
      const copy = res.clone();
      caches.open(CACHE).then((c) => c.put(req, copy));
    }
    return res;
  };
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req)
        .then(keep)
        .catch(() => caches.match(req, { ignoreSearch: true }).then((hit) => hit || caches.match('./index.html'))),
    );
    return;
  }
  event.respondWith(caches.match(req).then((hit) => hit || fetch(req).then(keep)));
});
`;
}

async function main() {
  const bundlePath = join(DIST, 'bundle.json');
  if (!existsSync(bundlePath)) {
    console.error(red('✗ dist/bundle.json not found; run scripts/build.ts first (pnpm build does both)'));
    process.exit(1);
  }
  const bundle = JSON.parse(readFileSync(bundlePath, 'utf8')) as Bundle;
  // Past statistics go to stats.js, loaded the first time a page shows them; the page keeps
  // which series have any. Everything else is inline, so the app opens offline and from file://.
  const { stats, areas, topics, ...data } = shippedData(bundle);
  data.past_series = [...new Set([...(stats ?? []), ...(areas ?? []), ...(topics ?? [])].map((x) => x.series))].sort();
  // MIT (ccfddl, lixin4ever) and CC BY (ACL Anthology) require their notices to ship with the app.
  data.notice = readFileSync(join(ROOT, 'NOTICE'), 'utf8');
  const statsJs = `// Generated by scripts/build-app.ts: past statistics for the app (MOBILE_SPEC §11.4), loaded on demand.\nwindow.NV_STATS=${JSON.stringify({ stats, areas, topics })};\n`;

  const esbuild = loadEsbuild();
  const js = await esbuild.build({
    entryPoints: [join(APP, 'main.ts')],
    bundle: true,
    write: false,
    format: 'iife',
    minify: true,
    target: ['es2020', 'safari15', 'chrome90'],
    charset: 'utf8',
    legalComments: 'none',
  });
  const script = (js.outputFiles?.[0]?.text ?? '').replace(/<\/script/gi, '<\\/script');
  const css = (
    await esbuild.transform(readFileSync(join(APP, 'style.css'), 'utf8'), {
      loader: 'css',
      minify: true,
      target: ['safari15', 'chrome90'],
      legalComments: 'none',
    })
  ).code.trim();
  const json = JSON.stringify(data).replace(/</g, '\\u003c');

  const html = readFileSync(join(APP, 'index.html'), 'utf8')
    .replace('/*STYLE*/', () => css)
    .replace('/*DATA*/', () => json)
    .replace('/*SCRIPT*/', () => script);

  mkdirSync(SITE, { recursive: true });
  const man = manifest();
  writeFileSync(join(SITE, 'index.html'), html);
  writeFileSync(join(SITE, 'stats.js'), statsJs);
  writeFileSync(join(SITE, 'manifest.webmanifest'), man);
  copyFileSync(join(APP, 'icon.svg'), join(SITE, 'icon.svg'));
  for (const f of ICON_FILES) {
    const png = join(APP, 'icons', f);
    if (!existsSync(png)) {
      console.error(red(`✗ ${png} missing; run pnpm icons to regenerate the PNG icons`));
      process.exit(1);
    }
    copyFileSync(png, join(SITE, f));
  }
  const version = createHash('sha256').update(html).update(statsJs).update(man).digest('hex').slice(0, 12);
  writeFileSync(join(SITE, 'sw.js'), serviceWorker(version));

  const kb = (s: string) => `${(Buffer.byteLength(s) / 1024).toFixed(0)} KB`;
  const byDisc = Object.entries(sizeByDiscipline(data))
    .sort((a, b) => b[1] - a[1])
    .map(([d, n]) => `${d} ${(n / 1024).toFixed(0)}`)
    .join(', ');
  console.log(
    green(
      `✓ built app → dist/site/index.html (${kb(html)}: data ${kb(json)}, js ${kb(script)}, css ${kb(css)}), stats.js (${kb(statsJs)}), manifest, sw.js, icons`,
    ),
  );
  console.log(`  editions + rules by 学科 (KB): ${byDisc}`);
}

await main();
